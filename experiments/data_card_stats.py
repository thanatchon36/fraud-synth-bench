"""Generate docs/data/DATA_CARD_STATS.md: descriptive statistics of the `small` preset (seed 0).

Usage: uv run python experiments/data_card_stats.py
"""

from __future__ import annotations

from pathlib import Path

import polars as pl

from fraudlab.synth import generate, preset

OUT = Path("docs/data/DATA_CARD_STATS.md")


def md(df: pl.DataFrame) -> str:
    cols = df.columns
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.iter_rows():
        rows.append(
            "| " + " | ".join(f"{v:,.2f}" if isinstance(v, float) else str(v) for v in r) + " |"
        )
    return "\n".join(rows)


def main() -> None:
    ds = generate(preset("small", seed=0))
    df = ds.transactions.join(ds.labels, on="tx_id")
    s = ds.stats
    parts = [
        "# Data card statistics: `small` preset, seed 0",
        "",
        f"Generated by `experiments/data_card_stats.py`. Content hash `{ds.content_hash()[:16]}`.",
        "",
        "## Size",
        "",
        md(
            pl.DataFrame(
                {
                    "quantity": [
                        "transactions",
                        "fraud transactions",
                        "fraud rate",
                        "accounts",
                        "merchants",
                        "devices",
                        "edges (aggregated)",
                    ],
                    "value": [
                        f"{s['n_transactions']:,}",
                        f"{s['n_fraud']:,}",
                        f"{s['fraud_rate']:.4%}",
                        f"{s['n_accounts']:,}",
                        f"{s['n_merchants']:,}",
                        f"{s['n_devices']:,}",
                        f"{s['n_edges']:,}",
                    ],
                }
            )
        ),
        "",
        "## Fraud by scenario",
        "",
        md(
            df.filter(pl.col("is_fraud") == 1)
            .group_by("scenario")
            .agg(
                pl.len().alias("transactions"),
                pl.col("fraud_event_id").n_unique().alias("events"),
                pl.col("amount").median().alias("median_amount"),
                pl.col("observed_label").mean().alias("detected_share"),
            )
            .sort("scenario")
        ),
        "",
        "## Amounts (USD-like units)",
        "",
        md(
            df.group_by(
                pl.when(pl.col("is_fraud") == 1)
                .then(pl.lit("fraud"))
                .otherwise(pl.lit("legit"))
                .alias("class")
            )
            .agg(
                pl.col("amount").quantile(0.10).alias("p10"),
                pl.col("amount").median().alias("p50"),
                pl.col("amount").quantile(0.90).alias("p90"),
                pl.col("amount").quantile(0.99).alias("p99"),
                pl.col("amount").mean().alias("mean"),
            )
            .sort("class")
        ),
        "",
        "## Channel mix",
        "",
        md(
            df.group_by("channel")
            .agg(
                pl.len().alias("transactions"), pl.col("is_fraud").mean().mul(100).alias("fraud_%")
            )
            .sort("channel")
        ),
        "",
        "## Merchant category mix (legitimate)",
        "",
        md(
            df.filter(pl.col("is_fraud") == 0)
            .group_by("mcc")
            .agg(pl.len().alias("transactions"), pl.col("amount").median().alias("median_amount"))
            .with_columns(
                (pl.col("transactions") / pl.col("transactions").sum() * 100).alias("share_%")
            )
            .sort("transactions", descending=True)
        ),
        "",
        "## Hour of day (share of transactions, %)",
        "",
        md(
            df.with_columns((pl.col("timestamp").dt.hour() // 4 * 4).alias("hour_bucket"))
            .group_by("hour_bucket")
            .agg(
                (pl.col("is_fraud") == 0).sum().alias("legit"),
                (pl.col("is_fraud") == 1).sum().alias("fraud"),
            )
            .sort("hour_bucket")
            .with_columns(
                (pl.col("legit") / pl.col("legit").sum() * 100).alias("legit_%"),
                (pl.col("fraud") / pl.col("fraud").sum() * 100).alias("fraud_%"),
            )
            .select(
                pl.format("{}-{}h", "hour_bucket", pl.col("hour_bucket") + 4).alias("hours"),
                "legit_%",
                "fraud_%",
            )
            
        ),
        "",
        "## Label delay (observed fraud, days)",
        "",
        md(
            df.filter(pl.col("observed_label") == 1)
            .with_columns(
                (
                    (pl.col("label_available_at") - pl.col("timestamp")).dt.total_seconds() / 86400
                ).alias("delay_days")
            )
            .group_by(
                pl.when(pl.col("scenario") == "friendly_fraud")
                .then(pl.lit("friendly_fraud"))
                .otherwise(pl.lit("other fraud"))
                .alias("group")
            )
            .agg(
                pl.col("delay_days").min().alias("min"),
                pl.col("delay_days").median().alias("median"),
                pl.col("delay_days").max().alias("max"),
            )
            .sort("group")
        ),
        "",
        "## Device sharing (online/transfer transactions)",
        "",
        md(
            df.filter(pl.col("device_id").is_not_null())
            .group_by("device_id")
            .agg(
                pl.col("account_id").n_unique().alias("accounts"),
                pl.col("is_fraud").max().alias("any_fraud"),
            )
            .group_by(
                pl.when(pl.col("any_fraud") == 1)
                .then(pl.lit("device with fraud"))
                .otherwise(pl.lit("legit-only device"))
                .alias("device")
            )
            .agg(
                pl.len().alias("devices"),
                pl.col("accounts").mean().alias("mean_accounts"),
                (pl.col("accounts") >= 2).mean().mul(100).alias("shared_%"),
            )
            .sort("device")
        ),
        "",
    ]
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
